  /* ---------------- engine ---------------- */
  function fallbackLang() { return (window.CONFIG && window.CONFIG.DEFAULT_LANG) || 'pt'; }
  function langList() { return (window.CONFIG && window.CONFIG.LANGS) || ['pt']; }

  let current = fallbackLang();

  function setLang(code) {
    if (langList().indexOf(code) === -1) return false;   // invalid -> keep previous
    current = code;
    return true;
  }

  function lookup(dict, key) {
    if (!dict) return undefined;
    return key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), dict);
  }

  // resolve a key for the current language, falling back to DEFAULT_LANG
  function resolve(key) {
    let v = lookup(DICT[current], key);
    if (v == null) v = lookup(DICT[fallbackLang()], key);
    return v;
  }

  function fill(tpl, vars) {
    if (typeof tpl !== 'string') return tpl;
    return tpl.replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] != null) ? vars[k] : '');
  }

  // string lookup with interpolation; last resort is the key itself
  function t(key, vars) {
    const v = resolve(key);
    if (v == null) return key;
    if (typeof v === 'string') return fill(v, vars);
    return v;
  }

  // narration-array lookup (engine generate-time). Always returns an array.
  function arr(key) {
    const v = resolve(key);
    return Array.isArray(v) ? v : [];
  }

  // flat list of every leaf key in a language (used by the parity test)
  function flatKeys(obj, prefix) {
    const out = [];
    Object.keys(obj || {}).forEach(k => {
      const val = obj[k];
      const kk = prefix ? prefix + '.' + k : k;
      if (val && typeof val === 'object' && !Array.isArray(val)) out.push(...flatKeys(val, kk));
      else out.push(kk);
    });
    return out;
  }

  window.I18N = {
    get lang() { return current; },
    set lang(v) { setLang(v); },
    setLang,
    getLang: function () { return current; },
    t, arr, fill,
    langs: langList,
    keysOf: function (code) { return flatKeys(DICT[code]); },
    _dict: DICT,
  };
